"""Job scripts: the exact shell every study job runs, rendered and kept.

Each submission writes its script to ``<root>/jobs/<name>.sh`` and the ledger
records its path, its bsub argv and its job id, so any number in the study can
be traced to the command that produced it. Resources go on the bsub command
line (as scripts/submit_all.sh does), never inside the script, so the script
is the experiment and the argv is the allocation.
"""

from __future__ import annotations

import shlex
from pathlib import Path
from typing import Dict, List, Sequence

from .spec import Spec, to_cluster


def _q(x) -> str:
    return shlex.quote(str(x))


def format_argv(argv: Sequence[str]) -> str:
    """One flag (with its values) per continuation line."""
    lines, cur = [], []
    for a in argv:
        if str(a).startswith("--") and cur:
            lines.append(" ".join(_q(x) for x in cur))
            cur = []
        cur.append(a)
    lines.append(" ".join(_q(x) for x in cur))
    return " \\\n  ".join(lines)


def study_partition(spec: Spec, which: str = "partition") -> str:
    """The study's FROZEN copy of a partition file (made at init).

    Jobs reference this copy, never the checkout's: the partition path is part
    of the strict resume fingerprint, so a path that moved with the code tree
    would make a promotion's continuation refuse to resume.
    """
    return f"{spec.root}/inputs/{Path(spec.raw[which]).name}"


def preamble(spec: Spec, repo: str, title: str) -> List[str]:
    return [
        "#!/usr/bin/env bash",
        f"# {title}",
        f"# study {spec.name} -- generated by `sinkholes hpo`; do not edit, resubmit via the controller",
        "set -euo pipefail",
        f"cd {_q(repo)}",
        f"source {_q(spec.raw['conda_sh'])}",
        f"conda activate {_q(spec.raw['conda_env'])}",
        "export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True",
        'echo "host $(hostname)  job ${LSB_JOBID:-none}  start $(date -Is)"',
        "nvidia-smi --query-gpu=name,memory.total --format=csv,noheader || true",
        # The env also holds an editable install of the main checkout; the job
        # must run THIS tree's code, so it refuses to start otherwise.
        "python - <<'PY'",
        "import os, sys",
        "import sinkholes.training.train as t, sinkholes.inference.snapshot_eval as e",
        "root = os.path.realpath(os.getcwd())",
        "bad = [m.__file__ for m in (t, e) if not os.path.realpath(m.__file__).startswith(root + os.sep)]",
        "sys.exit(f'sinkholes imported from {bad}, not {root}') if bad else print('code from', root)",
        "PY",
    ]


def train_argv(spec: Spec, trial: Dict, *, time_budget_hours: float) -> List[str]:
    """`sinkholes train` for one trial; identical for every chunk of it."""
    f = spec.fixed
    g = spec.geometry(trial["geometry"])
    sched = trial["schedule"]
    p = trial["params"]
    argv = ["python", "-m", "sinkholes", "train",
            "--epochs", trial["target_epochs"],
            "--batch_size", g["batch_size"], "--accum_steps", g["accum_steps"],
            "--learning-rate", repr(float(p["lr"])),
            "--weight_decay", repr(float(p["weight_decay"])),
            "--pos_w", repr(float(p["pos_w"])),
            "--optimizer", f["optimizer"], "--beta1", f["beta1"], "--beta2", f["beta2"],
            "--seg_loss", f["seg_loss"], "--augment_flips", f["augment_flips"],
            "--lr_schedule", sched["lr_schedule"], "--min_lr", repr(float(sched["min_lr"]))]
    if sched["lr_schedule"] == "plateau":
        argv += ["--lr_patience", sched["lr_patience"], "--lr_factor", sched["lr_factor"]]
    if sched.get("lr_horizon"):
        argv += ["--lr_horizon", sched["lr_horizon"]]
    argv += ["--patience", f["patience"],
             "--patches_dir", to_cluster(spec.raw["patches_dir"]),
             "--partition_mode", "preset_by_intf", "--partition_file", study_partition(spec),
             "--patch_size", *f["patch_size"], "--stride", f["stride"]]
    if tuple(g["context_margin"]) != (0, 0):
        argv += ["--context_margin", *g["context_margin"]]
    argv += ["--add_temporal", "--k_prevs", spec.k_prevs, "--tattn_unet",
             "--tattn_dim", f["tattn_dim"], "--tattn_heads", f["tattn_heads"],
             "--tattn_layers", f["tattn_layers"], "--tattn_recurrence", f["tattn_recurrence"],
             "--tattn_fuse_skips", f["tattn_fuse_skips"],
             "--tattn_contrast" if f["tattn_contrast"] else "--no-tattn_contrast",
             "--tattn_qk_norm" if f["tattn_qk_norm"] else "--no-tattn_qk_norm",
             "--convlstm_hidden", f["convlstm_hidden"]]
    if f["add_ring_negatives"]:
        argv += ["--add_ring_negatives", "--neg_ring_inner", f["neg_ring_inner"],
                 "--neg_ring_outer", f["neg_ring_outer"], "--neg_per_pos", f["neg_per_pos"]]
    if f["amp"]:
        argv.append("--amp")
    argv += ["--save_best_only", "--sample_every", 10,
             "--snapshot_epochs", ",".join(str(e) for e in trial["snapshot_epochs"]),
             "--keep_prev_resume", "--eval_rng_isolation", "--strict_resume",
             "--fit_eval_samples", trial.get("fit_eval_samples", f["fit_eval_samples"]),
             "--time_budget_hours", time_budget_hours,
             "--seed", trial["seed"], "--job_name", trial["slug"],
             "--resume", to_cluster(trial["run_dir"])]
    return [str(a) for a in argv]


def train_script(spec: Spec, repo: str, trial: Dict, chunk: int, time_budget_hours: float) -> str:
    argv = train_argv(spec, trial, time_budget_hours=time_budget_hours)
    lines = preamble(spec, repo, f"train {trial['key']} chunk {chunk} -> epoch {trial['target_epochs']}")
    lines += ["", format_argv(argv),
              'echo "train chunk finished $(date -Is)"',
              f"cat {_q(to_cluster(trial['run_dir']))}/run_status.json"]
    return "\n".join(lines) + "\n"


def eval_argv(spec: Spec, trial: Dict, epochs: Sequence[int], out_dir: str) -> List[str]:
    ev = spec.evaluation
    argv = ["python", "-m", "sinkholes", "eval-snapshots"]
    for e in epochs:
        argv += ["--checkpoint", f"e{e:03d}={to_cluster(snapshot_file(trial, e))}"]
    argv += ["--partition", study_partition(spec), "--split", ev["split"],
             "--aoi_split", ev["aoi_split"],
             "--patches_dir", to_cluster(spec.raw["patches_dir"]),
             "--k_prevs", spec.k_prevs, "--arch", "tattn_unet",
             "--patch_size", *spec.fixed["patch_size"], "--data_stride", ev["data_stride"],
             "--rth", *ev["rth"], "--ith", ev["ith"], "--buffer", ev["buffer"],
             "--min_positives", ev["min_positives"],
             "--tile_batch", ev["tile_batch"][trial["geometry"]],
             "--out_dir", to_cluster(out_dir), "--cache_dir", to_cluster(cache_dir(spec))]
    if ev.get("save_maps"):
        argv.append("--save_maps")
    return [str(a) for a in argv]


def eval_script(spec: Spec, repo: str, trial: Dict, epochs: Sequence[int], out_dir: str) -> str:
    lines = preamble(spec, repo, f"evaluate {trial['key']} at epochs {list(epochs)}")
    lines += ["", format_argv(eval_argv(spec, trial, epochs, out_dir)),
              'echo "evaluation finished $(date -Is)"']
    return "\n".join(lines) + "\n"


def util_script(spec: Spec, repo: str, spec_path: str, what: str, extra: Sequence[str]) -> str:
    lines = preamble(spec, repo, f"{what} for study {spec.name}")
    argv = ["python", "-m", "sinkholes", "hpo", what, "--spec", to_cluster(spec_path), *extra]
    lines += ["", " ".join(_q(a) for a in argv)]
    return "\n".join(lines) + "\n"


def snapshot_file(trial: Dict, epoch: int) -> str:
    return f"{trial['run_dir']}/checkpoints/snapshots/epoch_{int(epoch):03d}.pt"


def cache_dir(spec: Spec) -> str:
    return f"{spec.root}/cache"


def write_script(path: str, text: str) -> str:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    p.chmod(0o755)
    return str(p)
